library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use IEEE.NUMERIC_STD.ALL;
use std.textio.all;
use IEEE.STD_LOGIC_TEXTIO.ALL;

entity tb_pipeline is
end tb_pipeline;

architecture sim of tb_pipeline is

    -- 12 MHz clock period
    -- ??? ???????? ?? ??? ?????? ???? ????? ???????? 83 ns ?? 83333 ps ??????
    constant CLK_PERIOD : time := 83.333 ns;

    -- UART bit period for 115200 baud
    -- 1 / 115200 = 8.6805 us
    constant BIT_PERIOD : time := 8681 ns;
    constant HALF_BIT   : time := 4340 ns;

    signal clk    : std_logic := '0';
    signal button : std_logic := '0';
    signal tx     : std_logic := '1';

    -- ???? ????? ??? UART
    file uart_text_file : text open write_mode is "uart_text.txt";

begin

    ---------------------------------------------------
    -- DUT instantiation
    ---------------------------------------------------
    uut: entity work.pipeline
        port map (
            BUTTON => button,
            clk    => clk,
            Tx     => tx
        );

    ---------------------------------------------------
    -- Clock generation: 12 MHz
    ---------------------------------------------------
    clk <= not clk after CLK_PERIOD / 2;

    ---------------------------------------------------
    -- UART receiver model inside testbench
    -- ?? ???? ?? ??????? ? ?? ???? ???? ????????
    ---------------------------------------------------
    process
        variable rx_byte : std_logic_vector(7 downto 0);
        variable l       : line;
    begin
        -- ??? ???? ???? ??????????
        wait until falling_edge(tx);

        -- ?????????? ??? ??????????
        wait for HALF_BIT;

        if tx = '0' then
            -- ?????? 8 ??? ????? LSB first
            for i in 0 to 7 loop
                wait for BIT_PERIOD;
                rx_byte(i) := tx;
            end loop;

            -- ??? ???? ?????????
            wait for BIT_PERIOD;

            -- ????? ?? ????? ????????
            report "UART byte received: " & integer'image(to_integer(unsigned(rx_byte)));

            -- ????? ?? ???? ?? ???? ???
            if rx_byte = x"0A" then
                -- Line Feed: ???? ?? ?? ???
                writeline(uart_text_file, l);
            else
                write(l, character'val(to_integer(unsigned(rx_byte))));
            end if;
        end if;
    end process;

    ---------------------------------------------------
    -- Button stimulus
    ---------------------------------------------------
    stim: process
    begin
        button <= '0';
        wait for 1 ms;

        ---------------------------------------------------
        -- ???? 1: ???? ?????
        -- ???? ???? ?? ?? ?????? ????? ?? ????? ????? ????? ???
        -- ?????? ???? ?? ???: 1,000,000 ????
        -- ?? 12MHz ??????? 83.3ms
        ---------------------------------------------------
        report "Case 1: Short button press - no TX expected";
        button <= '1';
        wait for 20 ms;
        button <= '0';
        wait for 20 ms;

        ---------------------------------------------------
        -- ???? 2: ???? ????
        -- ???? ?? ??? ????? ????? ???
        ---------------------------------------------------
        report "Case 2: Long button press - one TX expected";
        button <= '1';
        wait for 90 ms;
        button <= '0';
        wait for 10 ms;

        ---------------------------------------------------
        -- ???? 3: ???? ???? ??????
        ---------------------------------------------------
        report "Case 3: Long button press again - another TX expected";
        button <= '1';
        wait for 90 ms;
        button <= '0';
        wait for 10 ms;

        ---------------------------------------------------
        -- ???? 4: ????????? ???? ?????? ????
        -- ?? ???? ???? ?? ???? ??? ???? ?? ???? ??? ?????
        -- ??? ?? ?? ??? ??????????? ???? ??? ?????? ????? ???
        ---------------------------------------------------
        report "Case 4: Very long button hold - repeated TX may occur";
        button <= '1';
        wait for 500 ms;
        button <= '0';
        wait for 20 ms;

        report "Simulation finished. Check uart_text.txt";
        wait;
    end process;

end sim;